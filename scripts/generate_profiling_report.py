    md.append(f"\n**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  ")
    md.append(f"**Binary:** profile preset (v{cpu_data['summary'].get('version', 'N/A')})")

    # ── 1. Overall Summary ──────────────────────────────────────────────
    md.append("\n## 1. Overall Summary\n")
    if overall_speedup >= 1:
        md.append(f"**Overall: GPU mode is {overall_speedup:.2f}x FASTER**\n")
    else:
        md.append(f"**Overall: GPU mode is {1/overall_speedup:.2f}x SLOWER**\n")

    md.append("| Metric | CPU-only | GPU mode | Delta |")
    md.append("|--------|----------|----------|-------|")
    md.append(f"| Total wall time | {cpu_total:.1f}s | {gpu_total:.1f}s | {gpu_total - cpu_total:+.1f}s |")
    md.append(f"| GPU kernel time | — | {gpu_kernel_total:.1f}s | — |")
    if gpu_mem:
        md.append(f"| VRAM peak | {_fmt_bytes(cpu_mem.get('vram_peak_bytes', 0))} | {_fmt_bytes(gpu_mem.get('vram_peak_bytes', 0))} | — |")
        md.append(f"| VRAM delta | {_fmt_bytes(cpu_mem.get('vram_delta_bytes', 0))} | {_fmt_bytes(gpu_mem.get('vram_delta_bytes', 0))} | — |")
        md.append(f"| CPU RSS peak | {_fmt_bytes(cpu_mem.get('cpu_rss_peak_bytes', 0))} | {_fmt_bytes(gpu_mem.get('cpu_rss_peak_bytes', 0))} | — |")
    md.append("\n![Stage Timing](stage_timing.png)\n")

    # ── 2. Per-Stage Breakdown ──────────────────────────────────────────
    md.append("## 2. Per-Stage Breakdown\n")
    md.append("| Stage | CPU Time | %CPU | GPU Time | %GPU | GPU Kernel | Speedup |")
    md.append("|-------|----------|------|----------|------|------------|---------|")
    for s in GRAPH_STAGES:
        ct, gt, gk = cpu_trace[s], gpu_trace[s], gpu_kernel[s]
        cp = ct / cpu_total * 100 if cpu_total else 0
        gp = gt / gpu_total * 100 if gpu_total else 0
        sp = ct / gt if gt > 0 else 0
        gk_str = f"{gk:.2f}s" if gk > 0 else "—"
        sp_str = f"**{sp:.2f}x**" if sp > 1 else f"{sp:.2f}x"
        md.append(f"| {s.upper()} | {ct:.1f}s | {cp:.1f}% | {gt:.1f}s | {gp:.1f}% | {gk_str} | {sp_str} |")
    md.append("\n![Stage Pie](stage_pie.png)\n")
    md.append("\n![Speedup](speedup.png)\n")

    # ── 3. CPU Traced Functions ─────────────────────────────────────────
    md.append("## 3. CPU Traced Functions\n")
    for s in GRAPH_STAGES:
        fns = cpu_data['stages'].get(s, {}).get('trace_functions', [])
        if not fns:
            continue
        md.append(f"### {s.upper()} ({cpu_trace[s]:.1f}s, {len(fns)} functions)\n")
        md.append("| Function | Time | Calls | File |")
        md.append("|----------|------|-------|------|")
        for fn in fns[:10]:
            md.append(f"| `{fn['name']}` | {_fmt_s(fn['duration_us'])} | {fn['count']:,} | {fn.get('file', '')} |")
        md.append("")

    # ── 4. GPU Traced Functions ─────────────────────────────────────────
    md.append("## 4. GPU Traced Functions\n")
    for s in GRAPH_STAGES:
        fns = gpu_data['stages'].get(s, {}).get('trace_functions', [])
        if not fns:
            continue
        md.append(f"### {s.upper()} ({gpu_trace[s]:.1f}s, {len(fns)} functions)\n")
        md.append("| Function | Time | Calls | File |")
        md.append("|----------|------|-------|------|")
        for fn in fns[:10]:
            md.append(f"| `{fn['name']}` | {_fmt_s(fn['duration_us'])} | {fn['count']:,} | {fn.get('file', '')} |")
        md.append("")

    # ── 5. VTune Hotspots ───────────────────────────────────────────────
    md.append("## 5. VTune CPU Hotspot Functions\n")
    md.append("![VTune Hotspots](vtune_hotspots.png)\n")
    for mode_label, data in [("CPU-only", cpu_data), ("GPU mode", gpu_data)]:
        for s in GRAPH_STAGES:
            fns = data['stages'].get(s, {}).get('vtune_minimap2_functions', [])
            if not fns:
                continue
            total_ms = data['stages'][s].get('vtune_minimap2_total_ms', 0)
            md.append(f"### {mode_label}: {s.upper()} ({total_ms/1000:.1f}s VTune time, {len(fns)} functions)\n")
            md.append("| Function | CPU Time |")
            md.append("|----------|----------|")
            for fn in fns[:10]:
                md.append(f"| `{fn['name']}` | {fn['cpu_time_ms']/1000:.2f}s |")
            md.append("")

    # ── 6. GPU Kernel Bottleneck Analysis ───────────────────────────────
    md.append("## 6. GPU Kernel Bottleneck Analysis\n")
    md.append("![Kernel Bottleneck](kernel_bottleneck.png)\n")
    for stage in GRAPH_STAGES + ['gpu_other']:
        kernels = gpu_data['stages'].get(stage, {}).get('gpu_kernels', [])
        if not kernels:
            continue
        stage_gpu = gpu_data['stages'][stage].get('gpu_time_us', 0) / 1e6
        md.append(f"### {stage.upper()} ({stage_gpu:.2f}s GPU kernel time)\n")
        md.append("| Kernel | Total | Calls | Avg/Call | % GPU |")
        md.append("|--------|-------|-------|----------|-------|")
        total_gpu_us = gpu_data['summary']['total_gpu_time_us']
        for k in kernels:
            name = k['name'].split('(')[0].strip()[:50]
            dur = k['duration_us'] / 1e6
            cnt = k['count']
            avg = k['duration_us'] / cnt if cnt else 0
            pct = k['duration_us'] / total_gpu_us * 100 if total_gpu_us else 0
            md.append(f"| `{name}` | {dur:.2f}s | {cnt:,} | {_fmt_s(avg)} | {pct:.1f}% |")
        md.append("")

    # ── 7. GPU Kernel Occupancy & CU Utilization ──────────────────────
    kernel_occ = gpu_data.get('kernel_occupancy', [])
    if kernel_occ:
        md.append("## 7. GPU Kernel Occupancy & CU Utilization\n")
        md.append("Theoretical occupancy and Compute-Unit (CU) coverage per dispatch, "
                  "derived from kernel register/LDS usage and grid dimensions in the "
                  "rocprofv3 trace.\n")
        md.append("| Kernel | Dispatches | Total | Avg | WG | Grid | VGPRs | LDS | Occupancy | CU Coverage |")
        md.append("|--------|-----------|-------|-----|-----|------|-------|-----|-----------|-------------|")
        for k in kernel_occ:
            short_name = k['name'].split('(')[0].strip()
            # Truncate template args for readability
            if '<' in short_name and len(short_name) > 45:
                short_name = short_name[:short_name.index('<') + 1] + '…>'
            elif len(short_name) > 45:
                short_name = short_name[:42] + '…'
            total_s = k['total_time_us'] / 1e6
            avg_s = k['avg_time_us'] / 1e6
            vgpr_str = f"{k['arch_vgpr']}"
            if k['accum_vgpr'] > 0:
                vgpr_str += f"+{k['accum_vgpr']}a"
            lds_str = f"{k['lds_bytes']:,}B" if k['lds_bytes'] > 0 else "—"
            occ_str = f"{k['occupancy_pct']:.0f}%"
            cu_cov = k['cu_coverage_pct']
            cu_str = f"{cu_cov:.0f}%"
            if cu_cov < 50:
                cu_str = f"**{cu_cov:.1f}%** ⚠"
            md.append(f"| `{short_name}` | {k['dispatch_count']:,} | {total_s:.2f}s | "
                      f"{_fmt_s(k['avg_time_us'])} | {k['workgroup_size']} | "
                      f"{k['max_grid_size']:,} | {vgpr_str} | {lds_str} | {occ_str} | {cu_str} |")

        # Highlight severe underutilization
        underutilized = [k for k in kernel_occ if k['cu_coverage_pct'] < 50]
        if underutilized:
            md.append("\n### CU Utilization Findings\n")
            for k in underutilized:
                short_name = k['name'].split('(')[0].strip()
                md.append(f"- **`{short_name}`**: Grid={k['max_grid_size']:,} threads → "
                          f"{k['waves_per_dispatch']} wave(s) across {k['num_cus']} CUs = "
                          f"**{k['cu_coverage_pct']:.1f}% CU coverage**. "
                          f"Each dispatch uses only {k['waves_per_dispatch']} of {k['num_cus']} CUs. "
                          f"With {k['dispatch_count']:,} dispatches totaling "
                          f"{k['total_time_us']/1e6:.1f}s, this is the primary utilization bottleneck. "
                          f"Batching multiple queries per dispatch would dramatically improve CU occupancy.")
        md.append("")

    # ── 8. HIP API Overhead ─────────────────────────────────────────────
    md.append("## 8. HIP API Overhead\n")
    hip_calls_flat: List[Tuple[str, float, int]] = []
    hw_dma_entries: List[Tuple[str, float, int]] = []  # hardware DMA (memcpy_memcpy etc.)
    for stage in gpu_data['stages']:
        for h in gpu_data['stages'].get(stage, {}).get('gpu_api_calls', []):
            if h['name'].startswith('memcpy_'):
                hw_dma_entries.append((h['name'], h['duration_us'] / 1e6, h['count']))
            else:
                hip_calls_flat.append((h['name'], h['duration_us'] / 1e6, h['count']))
    hip_calls_flat.sort(key=lambda x: -x[1])
    top_hip = hip_calls_flat[:10]
    if top_hip:
        md.append("![HIP API Overhead](hip_api_overhead.png)\n")
        md.append("| API Call | Total Time | Calls | Avg/Call |")
        md.append("|----------|-----------|-------|---------|")
        for name, t, cnt in top_hip:
            avg = t / cnt if cnt else 0
            md.append(f"| `{name}` | {t:.2f}s | {cnt:,} | {_fmt_s(avg * 1e6)} |")
        total_hip_time = sum(t for _, t, _ in hip_calls_flat)
        sync_time = next((t for n, t, _ in hip_calls_flat if n == 'hipDeviceSynchronize'), 0)
        real_overhead = total_hip_time - sync_time
        if gpu_kernel_total > 0:
            md.append(f"\n**Total HIP API time:** {total_hip_time:.1f}s "
                      f"(of which {sync_time:.1f}s is sync-wait overlapping kernel execution)  ")
            md.append(f"**Real HIP API overhead:** {real_overhead:.1f}s "
                      f"({real_overhead / gpu_kernel_total * 100:.1f}% of kernel time)")
        md.append("")

    # ── Synchronization & Overlap Analysis (subsection of HIP API) ─────
    gpu_api_all = extract_gpu_api_calls(gpu_data)
    gpu_kernels_all = extract_gpu_kernels(gpu_data)
    gpu_kernel_total_us = gpu_data['summary']['total_gpu_time_us']
    sync_analysis = analyze_sync_overlap(gpu_api_all, gpu_kernels_all, gpu_kernel_total_us)
    if sync_analysis:
        sa = sync_analysis
        md.append("### Synchronization & Overlap Analysis\n")
        md.append(f"`hipDeviceSynchronize` accounts for {sa['sync_time_us']/1e6:.1f}s "
                  f"({sa['sync_count']:,} calls). `hipLaunchKernel` dispatched "
                  f"{sa['user_kernel_count']:,} user kernels. GPU kernel execution totals "
                  f"{gpu_kernel_total:.1f}s ({sa['kernel_count']:,} dispatches including "
                  f"runtime-internal copies/fills).\n")
        if sa['dominant_kernel']:
            dk_name, dk_time, dk_count = sa['dominant_kernel']
            md.append(f"**Dominant kernel:** `{dk_name}` — {dk_time/1e6:.1f}s, "
                      f"{dk_count:,} dispatches\n")
        if sa['is_sync_waiting']:
            reasons = []
            if sa['sync_matches_launches']:
                reasons.append(f"sync count ({sa['sync_count']:,}) ≈ launch count ({sa['user_kernel_count']:,})")
            if sa['sync_approx_kernel_time']:
                reasons.append(f"sync time ({sa['sync_time_us']/1e6:.1f}s) ≈ kernel time ({gpu_kernel_total:.1f}s)")
            md.append(f"**Pattern detected: SYNCHRONOUS DISPATCH** — {'; '.join(reasons)}. "
                      f"Each kernel launch is immediately followed by `hipDeviceSynchronize`. "
                      f"The sync time is **not** additional overhead — it simply waits for "
                      f"the async kernel to complete.\n")
        md.append("| Category | Time | Calls | Note |")
        md.append("|----------|------|-------|------|")
        md.append(f"| Sync wait (overlapped with kernels) | {sa['overlap_us']/1e6:.1f}s | "
                  f"{sa['sync_count']:,} | Not extra overhead |")
        md.append(f"| Memory alloc/free | {sa['alloc_time_us']/1e6:.1f}s | "
                  f"{sa['alloc_count']:,} | hipMalloc + hipFree + hipHostMalloc + hipHostFree |")
        md.append(f"| Memory copy | {sa['memcpy_time_us']/1e6:.1f}s | "
                  f"{sa['memcpy_count']:,} | hipMemcpy + hipMemcpyAsync |")
        md.append(f"| Kernel launch | {sa['launch_time_us']/1e6:.1f}s | — | "
                  f"hipLaunchKernel + push/pop config |")
        md.append(f"| Memory set | {sa['memset_time_us']/1e6:.1f}s | — | hipMemset* |")
        md.append(f"| **Real HIP API overhead** | **{sa['real_api_overhead_us']/1e6:.1f}s** | — | "
                  f"Excluding sync overlap |")
        if gpu_kernel_total_us > 0:
            md.append(f"\n**Real overhead vs kernel time:** "
                      f"{sa['real_api_overhead_us'] / gpu_kernel_total_us * 100:.1f}%")
        md.append("")

    # ── 9. Host <-> Device Transfers ────────────────────────────────────
    md.append("## 9. Host \u2194 Device Transfers\n")
    # Collect transfers from both gpu_transfers (hardware-level) and
    # gpu_api_calls entries containing 'memcpy' (HIP API level)
    md_transfers: List[dict] = []
    for stage in gpu_data['stages']:
        for t in gpu_data['stages'].get(stage, {}).get('gpu_transfers', []):
            md_transfers.append(t)
        for a in gpu_data['stages'].get(stage, {}).get('gpu_api_calls', []):
            if 'memcpy' in a.get('name', '').lower():
                md_transfers.append(a)
    if md_transfers:
        md.append("| Operation | Total Time | Calls | Bytes | BW (GB/s) | Layer |")
        md.append("|-----------|-----------|-------|-------|-----------|-------|")
        for t in sorted(md_transfers, key=lambda x: -x.get('duration_us', 0)):
            dur = t.get('duration_us', 0)
            cnt = t.get('count', 0)
            b = t.get('bytes_total', 0)
            bw = b / (dur / 1e6) / 1e9 if dur > 0 and b > 0 else 0
            name = t.get('direction', t.get('name', '?'))
            layer = 'DMA' if name.startswith('memcpy_') else 'HIP API'
            md.append(f"| `{name}` | {_fmt_s(dur)} | {cnt:,} | {_fmt_bytes(b)} | {bw:.1f} | {layer} |")
        # Compute DMA bandwidth from hardware-level entries (those with actual byte counts)
        dma_entries = [t for t in md_transfers if t.get('bytes_total', 0) > 0]
        total_dma_bytes = sum(t.get('bytes_total', 0) for t in dma_entries)
        total_dma_time = sum(t.get('duration_us', 0) for t in dma_entries)
        total_api_time = sum(t.get('duration_us', 0) for t in md_transfers)
        if total_dma_bytes > 0:
            dma_bw = total_dma_bytes / (total_dma_time / 1e6) / 1e9 if total_dma_time > 0 else 0
            eff_bw = total_dma_bytes / (total_api_time / 1e6) / 1e9 if total_api_time > 0 else 0
            md.append(f"\n**Total transferred:** {_fmt_bytes(total_dma_bytes)}  ")
            md.append(f"**DMA bandwidth:** {dma_bw:.1f} GB/s (hardware transfer time: {_fmt_s(total_dma_time)})  ")
            md.append(f"**Effective bandwidth:** {eff_bw:.1f} GB/s (including HIP API overhead: {_fmt_s(total_api_time)})")
    else:
        md.append("No memory copy operations found in profiling data.\n")

    # ── 10. Function Comparison ─────────────────────────────────────────
    md.append("\n## 10. Function Comparison (CPU \u2192 GPU)\n")
    # Build function maps using only the top-level (outermost) function per
    # name.  trace_functions may list both parent and nested children; taking
    # the max duration per name selects the outermost inclusive measurement
    # so we don't double-count nested chains.
    def _top_fn_map(data: dict) -> dict:
        m: dict = {}
        for s in GRAPH_STAGES:
            for fn in data['stages'].get(s, {}).get('trace_functions', []):
                name = fn['name']
                if name not in m or fn['duration_us'] > m[name][0]:
                    m[name] = (fn['duration_us'], s)
        return m
    cpu_fn_map = _top_fn_map(cpu_data)
    gpu_fn_map = _top_fn_map(gpu_data)

    replaced = [(name, dur, stage) for name, (dur, stage) in cpu_fn_map.items()
                if name not in gpu_fn_map]
    replaced.sort(key=lambda x: -x[1])
    if replaced:
        md.append("### Functions replaced by GPU\n")
        md.append("| Function | CPU Time | Stage |")
        md.append("|----------|----------|-------|")
        for name, dur, stage in replaced[:10]:
            md.append(f"| `{name}` | {_fmt_s(dur)} | {stage} |")
        total_replaced = sum(d for _, d, _ in replaced)
        md.append(f"\n**Total CPU compute replaced:** {_fmt_s(total_replaced)}")

    new_fns = [(name, dur, stage) for name, (dur, stage) in gpu_fn_map.items()
               if name not in cpu_fn_map]
    new_fns.sort(key=lambda x: -x[1])
    if new_fns:
        md.append("\n### New functions in GPU mode\n")
        md.append("| Function | GPU Time | Stage |")
        md.append("|----------|----------|-------|")
        for name, dur, stage in new_fns[:10]:
            md.append(f"| `{name}` | {_fmt_s(dur)} | {stage} |")

    # ── 11. Memory Timeline ─────────────────────────────────────────────
    md.append("\n## 11. GPU Memory Timeline\n")
    if os.path.exists(os.path.join(out_dir, 'memory_timeline.png')):
        md.append("![Memory Timeline](memory_timeline.png)\n")
    else:
        md.append("Memory timeline graph not available.\n")

    # ── 12. Bottleneck Identification & Recommendations ─────────────────
    md.append("## 12. Bottleneck Identification & Recommendations\n")
    bottleneck = max(GRAPH_STAGES, key=lambda s: gpu_trace[s])
    bn_pct = gpu_trace[bottleneck] / gpu_total * 100 if gpu_total else 0
    md.append(f"### Primary Bottleneck: **{bottleneck.upper()}**\n")
    md.append(f"- Wall time: {gpu_trace[bottleneck]:.1f}s ({bn_pct:.1f}% of GPU-mode total)")
    md.append(f"- GPU kernel time: {gpu_kernel[bottleneck]:.1f}s")
    bn_overhead = gpu_trace[bottleneck] - gpu_kernel[bottleneck]
    if gpu_kernel[bottleneck] > 0:
        md.append(f"- Host overhead: {bn_overhead:.1f}s ({bn_overhead/gpu_trace[bottleneck]*100:.0f}% of stage wall time)")
    bn_speedup = cpu_trace[bottleneck] / gpu_trace[bottleneck] if gpu_trace[bottleneck] > 0 else 0
    md.append(f"- vs CPU: {bn_speedup:.2f}x {'faster' if bn_speedup >= 1 else 'slower'}")

    md.append("\n### Recommendations\n")

    # CU underutilization — the most actionable finding when present
    kernel_occ = gpu_data.get('kernel_occupancy', [])
    underutilized = [k for k in kernel_occ if k['cu_coverage_pct'] < 50]
    if underutilized:
        # Sort by total time to highlight the biggest offender first
        underutilized.sort(key=lambda k: -k['total_time_us'])
        md.append("**Primary optimization target: kernel batching**\n")
        for k in underutilized:
            short_name = k['name'].split('(')[0].strip()
            md.append(f"- **`{short_name}`** uses only {k['cu_coverage_pct']:.1f}% of CUs "
                      f"({k['waves_per_dispatch']} wave(s) on {k['num_cus']} CUs per dispatch). "
                      f"With {k['dispatch_count']:,} serial dispatches totaling "
                      f"{k['total_time_us']/1e6:.1f}s, batching multiple queries per launch "
                      f"could reduce kernel time by up to "
                      f"{min(k['num_cus'] // max(k['waves_per_dispatch'], 1), k['dispatch_count']):.0f}x.")
        md.append("")

    for s in GRAPH_STAGES:
        sp = cpu_trace[s] / gpu_trace[s] if gpu_trace[s] > 0 else 0
        if sp < 1:
            overhead = gpu_trace[s] - cpu_trace[s]
            md.append(f"- **{s.upper()}** regression: {1/sp:.1f}x slower (+{overhead:.1f}s)")
            if s == 'alignment' and gpu_kernel.get(s, 0) > 0:
                host_time = gpu_trace[s] - gpu_kernel[s]
                md.append(f"  - GPU kernel: {gpu_kernel[s]:.1f}s, Host overhead: {host_time:.1f}s ({host_time/gpu_trace[s]*100:.0f}%)")
                md.append("  - Consider batch-launching GPU alignment kernels to reduce per-call overhead")
                for hip_name, hip_t, hip_cnt in hip_calls_flat:
                    if hip_name in ('hipMalloc', 'hipFree', 'hipDeviceSynchronize') and hip_cnt > 1000:
                        md.append(f"  - `{hip_name}` called {hip_cnt:,} times ({hip_t:.1f}s) — pool allocation recommended")
                    elif hip_name in ('hipHostMalloc', 'hipHostFree') and hip_cnt > 0 and hip_t > 1.0:
                        avg_ms = hip_t / hip_cnt * 1000
                        md.append(f"  - `{hip_name}` called {hip_cnt:,} times ({hip_t:.1f}s, {avg_ms:.0f}ms/call) "
                                  f"— pre-allocate pinned buffers or use a pinned memory pool")
        elif sp > 1:
            md.append(f"- **{s.upper()}** speedup: {sp:.1f}x faster (GPU saves {cpu_trace[s] - gpu_trace[s]:.1f}s)")

    # Memory footprint findings
    cpu_rss_peak = gpu_mem.get('cpu_rss_peak_bytes', 0) if gpu_mem else 0
    cpu_rss_peak_cpu = cpu_mem.get('cpu_rss_peak_bytes', 0) if cpu_mem else 0
    if cpu_rss_peak > 0 and cpu_rss_peak_cpu > 0 and cpu_rss_peak > 2 * cpu_rss_peak_cpu:
        ratio = cpu_rss_peak / cpu_rss_peak_cpu
        md.append(f"- **Memory footprint:** GPU mode uses {_fmt_bytes(cpu_rss_peak)} CPU RSS "
                  f"vs {_fmt_bytes(cpu_rss_peak_cpu)} in CPU-only mode ({ratio:.1f}x increase). "
                  f"Reducing per-alignment allocations (hipMalloc/hipFree) and reusing "
                  f"host-side buffers would lower RSS.")

    if overall_speedup < 1:
        md.append(f"\n**Projected improvement (host overhead):** Eliminating {bottleneck.upper()} "
                  f"host overhead ({bn_overhead:.0f}s) would bring GPU total to ~{gpu_total - bn_overhead:.0f}s")
        # Add kernel batching projection if CU underutilization data is available
        if underutilized:
            worst = underutilized[0]
            max_batch = min(worst['num_cus'] // max(worst['waves_per_dispatch'], 1),
                           worst['dispatch_count'])
            if max_batch > 1:
                kernel_time_s = worst['total_time_us'] / 1e6
                batched_kernel_s = kernel_time_s / max_batch
                batched_total = gpu_total - kernel_time_s + batched_kernel_s
                md.append(f"\n**Projected improvement (kernel batching):** Batching `{worst['name'].split('(')[0].strip()}` "
                          f"to fill all {worst['num_cus']} CUs would reduce its {kernel_time_s:.1f}s kernel time "
                          f"to ~{batched_kernel_s:.1f}s, bringing the GPU total to ~{batched_total:.0f}s "
                          f"({cpu_total / batched_total:.1f}x vs CPU)")

    # ── 13. Output Files ────────────────────────────────────────────────
    md.append("\n## 13. Output Files\n")
    md.append("| File | Description |")
    md.append("|------|-------------|")
    md.append("| `analysis.json` | Structured profiling data |")
    md.append("| `trace.log` | Minimap2 trace timing output |")
    md.append("| `vtune/` | VTune raw profiling data |")
    md.append("| `rocprof/` | rocprofv3 kernel/HIP trace data |")
    md.append("| `logs/` | Tool run logs (vtune_run.log, rocprof_run_*.log) |")
    md.append("| `memory_timeline.png` | GPU/CPU memory usage over time |")

    md_text = '\n'.join(md) + '\n'
    report_path = os.path.join(out_dir, 'PROFILING_REPORT.md')
    with open(report_path, 'w') as f:
        f.write(md_text)
    print(f"Report: {report_path}")


