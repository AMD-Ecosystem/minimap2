# CLI entry point
# ═══════════════════════════════════════════════════════════════════════════

def main():
    parser = argparse.ArgumentParser(
        description="Generate CPU vs GPU profiling comparison report",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument('cpu_analysis', type=Path,
                        help='Path to CPU-only analysis.json')
    parser.add_argument('gpu_analysis', type=Path,
                        help='Path to GPU analysis.json')
    parser.add_argument('--output-dir', '-o', type=str, default=None,
                        help='Directory for Markdown report and graphs (optional)')

    args = parser.parse_args()

    if not args.cpu_analysis.exists():
        print(f"Error: CPU analysis file not found: {args.cpu_analysis}", file=sys.stderr)
        sys.exit(1)
    if not args.gpu_analysis.exists():
        print(f"Error: GPU analysis file not found: {args.gpu_analysis}", file=sys.stderr)
        sys.exit(1)

    cpu_data = load_analysis(args.cpu_analysis)
    gpu_data = load_analysis(args.gpu_analysis)

    # Always print text comparison to stdout
    print_comparison(cpu_data, gpu_data, args.cpu_analysis, args.gpu_analysis)

    # Generate graphs + Markdown report if output dir specified
    if args.output_dir:
        os.makedirs(args.output_dir, exist_ok=True)
        generate_graphs(cpu_data, gpu_data, args.output_dir)
        generate_markdown_report(cpu_data, gpu_data, args.output_dir)
        graph_files = [f for f in sorted(os.listdir(args.output_dir)) if f.endswith('.png')]
        print(f"\nGenerated {len(graph_files)} graphs:")
        for f in graph_files:
            print(f"  {f}")


if __name__ == '__main__':
    main()
