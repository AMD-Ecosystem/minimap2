def _collect_stage_times(cpu_data: dict, gpu_data: dict) -> Tuple[dict, dict, dict, float, float, float]:
    """Collect per-stage trace/kernel times and totals for graphs."""
    cpu_trace = {s: cpu_data['stages'].get(s, {}).get('trace_time_us', 0) / 1e6 for s in GRAPH_STAGES}
    gpu_trace = {s: gpu_data['stages'].get(s, {}).get('trace_time_us', 0) / 1e6 for s in GRAPH_STAGES}
    gpu_kernel = {s: gpu_data['stages'].get(s, {}).get('gpu_time_us', 0) / 1e6 for s in GRAPH_STAGES}
    cpu_total = cpu_data['summary']['total_trace_time_us'] / 1e6
    gpu_total = gpu_data['summary']['total_trace_time_us'] / 1e6
    gpu_kernel_total = gpu_data['summary']['total_gpu_time_us'] / 1e6
    return cpu_trace, gpu_trace, gpu_kernel, cpu_total, gpu_total, gpu_kernel_total


