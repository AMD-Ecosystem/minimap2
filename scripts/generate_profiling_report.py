def load_analysis(path: Path) -> dict:
    """Load analysis.json file."""
    with open(path) as f:
        return json.load(f)


def extract_trace_functions(data: dict) -> Dict[str, dict]:
    """Extract all trace functions from analysis data."""
    funcs = {}
    for stage, sdata in data.get('stages', {}).items():
        for func in sdata.get('trace_functions', []):
            name = func.get('name', '')
            if name:
                if name not in funcs:
                    funcs[name] = {
                        'time_us': 0,
                        'count': 0,
                        'file': func.get('file', ''),
                        'stage': stage,
                        '_stage_time': {},
                    }
                funcs[name]['time_us'] += func.get('duration_us', 0)
                funcs[name]['count'] += func.get('count', 0)
                st = funcs[name]['_stage_time']
                st[stage] = st.get(stage, 0) + func.get('duration_us', 0)
    for info in funcs.values():
        st = info.pop('_stage_time')
        if st:
            info['stage'] = max(st, key=st.get)
    return funcs


def extract_gpu_kernels(data: dict) -> Dict[str, dict]:
    """Extract all GPU kernels from analysis data."""
    kernels = {}
    for stage, sdata in data.get('stages', {}).items():
        for kernel in sdata.get('gpu_kernels', []):
            name = kernel.get('name', '')
            if name:
                short_name = shorten_kernel_name(name)
                if short_name not in kernels:
                    kernels[short_name] = {
                        'full_name': name,
                        'time_us': 0,
                        'count': 0,
                        'stage': stage,
                    }
                kernels[short_name]['time_us'] += kernel.get('duration_us', 0)
                kernels[short_name]['count'] += kernel.get('count', 0)
    return kernels


def extract_kernel_counters(data: dict) -> Dict[str, dict]:
    """Extract kernel hardware counter data from analysis data."""
    raw = data.get('kernel_counters', {})
    if not raw:
        return {}
    counters = {}
    for name, info in raw.items():
        short = shorten_kernel_name(name)
        existing = counters.get(short)
        if existing is None or info.get('dispatch_count', 0) > existing.get('dispatch_count', 0):
            counters[short] = info
    return counters


def extract_gpu_api_calls(data: dict) -> Dict[str, dict]:
    """Extract all GPU API calls (HIP/HSA) across stages."""
    calls: Dict[str, dict] = {}
    for stage, sdata in data.get('stages', {}).items():
        for call in sdata.get('gpu_api_calls', []):
            name = call.get('name', '')
            if not name:
                continue
            if name not in calls:
                calls[name] = {'time_us': 0, 'count': 0, 'bytes_total': 0, 'stage': stage}
            calls[name]['time_us'] += call.get('duration_us', 0)
            calls[name]['count'] += call.get('count', 0)
            calls[name]['bytes_total'] += call.get('bytes_total', 0)
    return calls


def extract_transfers(api_calls: Dict[str, dict]) -> Dict[str, dict]:
    """Filter API calls to Host<->Device memory copy operations."""
    return {n: v for n, v in api_calls.items() if 'memcpy' in n.lower()}


def analyze_sync_overlap(gpu_api_calls: Dict[str, dict],
                        gpu_kernels: Dict[str, dict],
                        gpu_kernel_total_us: float) -> Optional[Dict[str, Any]]:
    """Detect whether hipDeviceSynchronize time overlaps with kernel execution.

    When kernels are launched asynchronously and each launch is followed by a
    sync call, the sync duration equals the kernel duration (it's just waiting).
    This function identifies that pattern and computes the real non-overlapping
    HIP API overhead."""
    sync_info = gpu_api_calls.get('hipDeviceSynchronize')
    if not sync_info:
        return None

    sync_time_us = sync_info['time_us']
    sync_count = sync_info['count']

    # Total dispatched kernel count (all kernels including runtime internals)
    total_kernel_count = sum(k['count'] for k in gpu_kernels.values())
    # User-launched kernel count (from hipLaunchKernel API)
    launch_info = gpu_api_calls.get('hipLaunchKernel', {})
    user_kernel_count = launch_info.get('count', 0)

    # Detect sync pattern by comparing sync count with user kernel launches
    # (runtime-internal kernels like __amd_rocclr_copyBuffer are not user-launched)
    sync_matches_launches = (user_kernel_count > 0 and
                             abs(sync_count - user_kernel_count) / user_kernel_count < 0.05)
    # Also check if sync time ≈ kernel time (within 20% tolerance)
    sync_approx_kernel_time = (gpu_kernel_total_us > 0 and
                               abs(sync_time_us - gpu_kernel_total_us) / gpu_kernel_total_us < 0.20)

    is_sync_waiting = sync_matches_launches or sync_approx_kernel_time

    # The overlap is the portion of sync time that's just waiting for kernels
    overlap_us = min(sync_time_us, gpu_kernel_total_us) if is_sync_waiting else 0
    sync_overhead_us = sync_time_us - overlap_us

    # Compute real (non-sync-wait) HIP API overhead
    all_hip_time_us = sum(v['time_us'] for n, v in gpu_api_calls.items()
                         if n.startswith('hip'))
    real_api_overhead_us = all_hip_time_us - overlap_us

    # Categorize HIP API calls
    alloc_time = sum(v['time_us'] for n, v in gpu_api_calls.items()
                     if n in ('hipMalloc', 'hipFree', 'hipHostMalloc', 'hipHostFree'))
    alloc_count = sum(v['count'] for n, v in gpu_api_calls.items()
                      if n in ('hipMalloc', 'hipFree', 'hipHostMalloc', 'hipHostFree'))
    # Only count HIP API-level memcpy calls (hip*), not hardware DMA entries (memcpy_*)
    memcpy_time = sum(v['time_us'] for n, v in gpu_api_calls.items()
                      if 'memcpy' in n.lower() and n.startswith('hip'))
    memcpy_count = sum(v['count'] for n, v in gpu_api_calls.items()
                       if 'memcpy' in n.lower() and n.startswith('hip'))
    launch_time = sum(v['time_us'] for n, v in gpu_api_calls.items()
                      if 'launch' in n.lower() or 'push' in n.lower() or 'pop' in n.lower())
    memset_time = sum(v['time_us'] for n, v in gpu_api_calls.items()
                      if 'memset' in n.lower())

    # Find which kernel the syncs are likely waiting for
    dominant_kernel = max(gpu_kernels.items(), key=lambda x: x[1]['time_us']) if gpu_kernels else None

    return {
        'sync_time_us': sync_time_us,
        'sync_count': sync_count,
        'kernel_count': total_kernel_count,
        'user_kernel_count': user_kernel_count,
        'is_sync_waiting': is_sync_waiting,
        'sync_matches_launches': sync_matches_launches,
        'sync_approx_kernel_time': sync_approx_kernel_time,
        'overlap_us': overlap_us,
        'sync_overhead_us': sync_overhead_us,
        'all_hip_time_us': all_hip_time_us,
        'real_api_overhead_us': real_api_overhead_us,
        'alloc_time_us': alloc_time,
        'alloc_count': alloc_count,
        'memcpy_time_us': memcpy_time,
        'memcpy_count': memcpy_count,
        'launch_time_us': launch_time,
        'memset_time_us': memset_time,
        'dominant_kernel': (dominant_kernel[0], dominant_kernel[1]['time_us'],
                           dominant_kernel[1]['count']) if dominant_kernel else None,
    }


